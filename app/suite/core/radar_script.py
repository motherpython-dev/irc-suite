"""Сценарий радара для демо и «Индикатор всегда» — варианты из мокапа в движении.

В прошлой гонке нет места машины поперёк трассы, поэтому радар в демо не
строится из неё, а показывает то же, что мокап: заход, тривайд (вы в середине,
сверху, снизу), соседний поезд. Каждый вариант идёт VARIANT_S секунд: машины
заходят сзади, встают как в мокапе, чуть «дышат» и уходят вперёд — без рывков.

Положение — dm, метры: + впереди, − сзади, от середины вашей машины; lane — две
дорожки с одной стороны (тривайд, когда обе машины по одну сторону от вас).
"""
from __future__ import annotations

import math

VARIANT_S = 5.0                 # секунд на вариант
IN_S, OUT_S = 0.9, 0.9          # заезд сзади и уход вперёд внутри варианта

# варианты мокапа, dm — в долях длины машины (L = 5 м, зазор поезда 0,2 м)
_T = 1.04                       # длина машины + зазор, в долях длины
VARIANTS = (
    # заход слева: машина сзади поравнялась и ушла вперёд
    ("заход", [{"s": "l", "dm": 0.0}]),
    ("тривайд: вы в середине", [{"s": "l", "dm": 0.32}, {"s": "r", "dm": -0.26}]),
    ("тривайд: вы сверху", [{"s": "l", "dm": 0.28, "lane": 1}, {"s": "l", "dm": -0.36, "lane": 0}]),
    ("тривайд: вы снизу", [{"s": "r", "dm": 0.36, "lane": 0}, {"s": "r", "dm": -0.28, "lane": 1}]),
    ("поезд справа", [{"s": "r", "dm": -0.44}, {"s": "r", "dm": -0.44 + _T},
                      {"s": "r", "dm": -0.44 + 2 * _T}, {"s": "r", "dm": -0.44 - _T}]),
)


def _ease(x: float) -> float:
    x = max(0.0, min(1.0, x))
    return x * x * (3 - 2 * x)


def radar_script(now: float, car_m: float) -> list[dict]:
    """Машины рядом на момент now (секунды, монотонные), car_m — длина машины, м."""
    k = int(now // VARIANT_S) % len(VARIANTS)
    t = now % VARIANT_S
    # общий сдвиг варианта: из-за спины (−1,6 длины) на место, потом вперёд (+1,6)
    if t < IN_S:
        shift = -1.6 * (1 - _ease(t / IN_S))
    elif t > VARIANT_S - OUT_S:
        shift = 1.6 * _ease((t - (VARIANT_S - OUT_S)) / OUT_S)
    else:
        shift = 0.0
    name, cars = VARIANTS[k]
    out = []
    for i, c in enumerate(cars):
        breathe = 0.06 * math.sin(now * 1.3 + i * 1.7)     # машины чуть гуляют, как в жизни
        if name == "заход":
            # одиночная машина проходит вдоль вас целиком: сзади → вровень → вперёд
            dm = -1.1 + 2.2 * _ease(t / VARIANT_S)
        elif name == "поезд справа":
            dm = c["dm"] + shift + 0.12 * math.sin(now * 0.8)   # соседний поезд едет чуть быстрее/медленнее
        else:
            dm = c["dm"] + shift + breathe
        if abs(dm) >= 1.0:
            continue                                        # не перекрывает — на радаре её нет
        x = {"s": c["s"], "dm": round(dm * car_m, 2)}
        if "lane" in c:
            x["lane"] = c["lane"]
        out.append(x)
    return out
